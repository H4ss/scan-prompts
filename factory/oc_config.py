"""Generate the opencode config of one ticket worktree from the ticket contract.

Target syntax: opencode V2 (`permissions` list, `agents` map, `system`, `steps`, `disabled`), as
documented on opencode.ai/docs on 2026-11-23. Rules are ordered; the last matching rule wins.
Built-in agents are disabled and a top-level deny-all applies, so switching agent does not
escape the frame. To check on the installed version with the permission probe before use.
"""
from __future__ import annotations

import fnmatch
import json
from pathlib import Path

import frontmatter

HERE = Path(__file__).resolve().parent
AGENTS_DIR = HERE.parent / "opencode" / "agents"

NO_GO_ACTIONS = ["webfetch", "websearch", "subagent", "skill", "question", "generate_image"]
SECRET_GLOBS = ["*.env", "*.env.*", "*.pem", "*.key", "*id_rsa*"]
BUILTIN_AGENTS = ["build", "plan", "general", "explore"]
REVIEW_SHELL = ["git diff *", "git log *", "git show *", "git status *"]


def _rule(action: str, resource: str, effect: str) -> dict:
    return {"action": action, "resource": resource, "effect": effect}


def _reads(policy: dict) -> list:
    rules = [_rule(a, "*", "allow") for a in ("read", "glob", "grep")]
    rules += [_rule("read", g, "deny") for g in SECRET_GLOBS]
    rules += [_rule("read", g, "allow") for g in policy.get("append_only", [])]  # secret-like corpus samples
    return rules


def dev_permissions(ticket: dict, policy: dict, fx_path: str) -> list:
    oc = policy.get("opencode", {})
    rules = [_rule("*", "*", "deny")] + _reads(policy)
    rules += [_rule("edit", g, "allow") for g in ticket.get("allowed_paths") or []]
    rules += [_rule("edit", g, "deny") for g in policy.get("unlockable", [])]
    rules += [_rule("edit", g, "deny") for g in (ticket.get("forbidden_paths") or []) + policy.get("protected", [])]
    corpus = [g for g in ticket.get("allowed_paths") or [] if any(fnmatch.fnmatchcase(g, a) for a in policy.get("append_only", []))]
    rules += [_rule("edit", g, "allow") for g in corpus]  # new corpus cases may hold AGENTS.md, manifests...
    rules += [_rule("edit", p, "allow") for p in ticket.get("unlock") or []]
    rules += [_rule("shell", p.replace("{fx}", fx_path), "allow") for p in oc.get("shell_allow", [])]
    rules += [_rule("shell", p, "deny") for p in oc.get("shell_deny_after_allow", [])]
    rules += [_rule("external_directory", "*", "deny"), _rule("external_directory", fx_path, "allow")]
    rules += [_rule(a, "*", "deny") for a in NO_GO_ACTIONS]
    return rules


def review_permissions(policy: dict) -> list:
    rules = [_rule("*", "*", "deny")] + _reads(policy)
    rules += [_rule("shell", p, "allow") for p in REVIEW_SHELL]
    rules += [_rule("shell", p, "deny") for p in policy.get("opencode", {}).get("shell_deny_after_allow", [])]
    rules += [_rule(a, "*", "deny") for a in NO_GO_ACTIONS + ["edit", "external_directory"]]
    return rules


def _system(name: str, fx_path: str, base: str) -> str:
    _, body = frontmatter.load(AGENTS_DIR / f"{name}.md")
    return body.strip().replace("<fx>", fx_path).replace("<base>", base)


def build(ticket: dict, policy: dict, fx_path: str, model, base: str) -> dict:
    steps = int(policy.get("defaults", {}).get("agent_steps", 60))
    agents = {name: {"disabled": True} for name in BUILTIN_AGENTS}
    agents["factory-dev"] = {
        "description": f"Implements ticket {ticket['id']} inside its allowed paths only",
        "mode": "primary", "steps": steps,
        "system": _system("factory-dev", fx_path, base),
        "permissions": dev_permissions(ticket, policy, fx_path),
    }
    agents["factory-review"] = {
        "description": f"Read-only review of ticket {ticket['id']}",
        "mode": "primary", "steps": steps,
        "system": _system("factory-review", fx_path, base),
        "permissions": review_permissions(policy),
    }
    if model:
        agents["factory-dev"]["model"] = model
        agents["factory-review"]["model"] = model
    return {
        "$schema": "https://opencode.ai/config.json",
        "default_agent": "factory-dev",
        "permissions": [_rule("*", "*", "deny")],
        "agents": agents,
    }


def render(ticket: dict, policy: dict, fx_path: str, model, base: str) -> str:
    header = f"// Generated by fx.py from ticket {ticket['id']}. Do not edit: 'fx.py amend' regenerates it.\n"
    return header + json.dumps(build(ticket, policy, fx_path, model, base), indent=2) + "\n"


def write(worktree, ticket: dict, policy: dict, fx_path: str, model, base: str) -> Path:
    out = Path(worktree) / ".opencode" / "opencode.jsonc"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(ticket, policy, fx_path, model, base), encoding="utf-8", newline="\n")
    return out
